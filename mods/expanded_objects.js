// Этот файл дополняет словари для объектов
const addThoughts = (id, data) => {
  if (!Reg.composer.objects[id]) return; // Если объекта нет, пропускаем
  const obj = Reg.composer.objects[id];
  
  if (data.verbs) obj.verbs = obj.verbs.concat(data.verbs);
  if (data.adjectives) obj.adjectives = obj.adjectives.concat(data.adjectives);
  
  if (data.traits) {
    for (let key in data.traits) {
      if (obj.traits[key]) {
        // Если черта уже есть, просто добавляем новые тексты (собираем в массив)
        if (!Array.isArray(obj.traits[key].text)) obj.traits[key].text = [obj.traits[key].text];
        obj.traits[key].text = obj.traits[key].text.concat(data.traits[key].text);
      } else {
        obj.traits[key] = data.traits[key];
      }
    }
  }
};

