Reg.generateBackstory = function(npc) {
  const origins = [
    "из далеких горных чертогов", "из шумного человеческого города", 
    "из заброшенной деревни на границе", "из глубоких южных пещер", 
    "из портового города, пропахшего рыбой", "из лесного скита",
    "из крепости, павшей под натиском орков", "из земель вечной мерзлоты",
    "из подземного улья", "из города, сгоревшего дотла"
  ];
  
  const pastLives = [
    "был простым шахтером", "был странствующим торговцем", 
    "был наемником в чужой войне", "был фермером, потерявшим урожай", 
    "был писарем, уставшим от бумаг", "был бродягой, ночевавшим под мостами",
    "был кузнецом, чья мастерская сгорела", "был поваром, отравившим знатного лорда",
    "был библиотекарем, хранившим запретные книги", "был палачом, которому снились кошмары",
    "был пекарем, который так и не научился печь", "был стражником, уснувшим на посту"
  ];

  const reasons = [
    "пришел сюда в поисках несметных золотых жил", "сбежал от долгов и кредиторов", 
    "ищет своего пропавшего брата", "надеется найти древние артефакты", 
    "просто хочет выжить и прокормиться", "слышал легенды о сокровищах на самом дне",
    "хочет доказать отцу, что чего-то стоит", "сбежал от нежеланной свадьбы",
    "ищет искупления за старые грехи", "его ведет странный голос из-под земли",
    "хочет найти легендарный молот своего деда", "пытается забыть ужасы войны",
    "надеется, что под землей не будет солнца", "хочет стать величайшим кузнецом"
  ];

  const feelings = [
    "Он чувствует сожаление о прошлом.", "Он полон надежд на лучшее.", 
    "Он боится темноты, но не подает вида.", "Он озлоблен на весь мир.", 
    "Он скучает по солнцу.", "Ему все равно, лишь бы платили.",
    "Он одержим идеей найти мифрил.", "Он ненавидит эльфов и деревья.",
    "Он постоянно голоден.", "Он не доверяет никому вокруг."
  ];

  const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
  
  let past = pick(pastLives);
  if (npc.profession.id === 'smith') past = pick(["был кузнецом, чья мастерская сгорела", "выковывал клинки для павшего короля"]);
  
  let feel = pick(feelings);
  if (npc.facets && npc.facets.religiosity > 70) feel = "Он верит, что боги направляют его кирку.";

  const origin = pick(origins);
  const reason = pick(reasons);

  const templates = [
    `Он прибыл ${origin}, где ${past}. Сюда он ${reason}. ${feel}`,
    `${feel} Когда-то он ${past} ${origin}. Теперь он ${reason}.`,
    `Раньше он ${past} ${origin}. ${reason.charAt(0).toUpperCase() + reason.slice(1)}. ${feel}`,
    `Его прошлое скрыто во тьме: он ${past} ${origin}. Он ${reason}.`
  ];

  return pick(templates);
};
